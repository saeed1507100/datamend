"""Reviewer feedback on agent runs, kept as lessons that later prompts include.

A person comments on a whole run (chat style) or on one step of its trajectory. The
comment becomes a lesson with a scope: `global`, `dataset:<name>`, or
`deployment:<name>`. Every later prompt for a matching scope lists the active lessons.
Lessons live in a small DuckDB file and export to Markdown for review in git.
"""

import uuid
from datetime import datetime
from pathlib import Path

from datamend.ai.trajectory import describe

SCHEMA = """
CREATE TABLE IF NOT EXISTS lessons (
    lesson_id VARCHAR PRIMARY KEY, scope VARCHAR, text VARCHAR, run_id VARCHAR,
    step INTEGER, step_summary VARCHAR, feedback VARCHAR, author VARCHAR,
    active BOOLEAN, created_at TIMESTAMP
)
"""


def init(con) -> None:
    con.execute(SCHEMA)


def scope_for(kind: str, name: str | None) -> str:
    return "global" if kind == "global" or not name else f"{kind}:{name}"


def lesson_text(feedback: str, step: dict | None) -> str:
    """The lesson as a later prompt will read it: the reviewer's words, with step context."""
    if step is None:
        return feedback.strip()
    return f"{feedback.strip()} (reviewer comment on a past step: {describe(step)})"


def add(con, *, run_id: str, feedback: str, scope: str, now: datetime,
        step: dict | None = None, author: str = "reviewer") -> dict:
    init(con)
    row = {"lesson_id": f"ls_{uuid.uuid4().hex[:8]}", "scope": scope,
           "text": lesson_text(feedback, step), "run_id": run_id,
           "step": step["n"] if step else None,
           "step_summary": None if step is None else describe(step),
           "feedback": feedback.strip(), "author": author, "active": True, "created_at": now}
    con.execute(f"INSERT INTO lessons ({', '.join(row)}) VALUES ({', '.join('?' * len(row))})",
                list(row.values()))
    return row


def all_lessons(con, include_inactive: bool = False) -> list[dict]:
    init(con)
    cur = con.execute("SELECT * FROM lessons " + ("" if include_inactive else "WHERE active ")
                      + "ORDER BY created_at, lesson_id")
    return [dict(zip([c[0] for c in cur.description], r)) for r in cur.fetchall()]


def forget(con, lesson_id: str) -> bool:
    init(con)
    found = con.execute("SELECT count(*) FROM lessons WHERE lesson_id = ? AND active",
                        [lesson_id]).fetchone()[0]
    con.execute("UPDATE lessons SET active = false WHERE lesson_id = ?", [lesson_id])
    return bool(found)


def select(lessons: list[dict] | None, *scopes: str) -> list[str]:
    """Texts of active lessons that apply: global ones plus those for any given scope."""
    wanted = {"global", *scopes}
    return [ls["text"] for ls in lessons or [] if ls.get("active", True) and ls["scope"] in wanted]


def prompt_section(texts: list[str]) -> str:
    if not texts:
        return ""
    return ("\n## Lessons from past reviews\nReviewers left these notes on earlier fixes. "
            "Follow them unless they conflict with the rules above.\n"
            + "\n".join(f"- {t}" for t in texts) + "\n")


def to_markdown(lessons: list[dict]) -> str:
    lines = ["# datamend lessons", "",
             ("Reviewer feedback that datamend adds to later agent prompts. "
             "Generated by `datamend ai lessons export`; edit with `datamend ai feedback` "
             "and `datamend ai lessons forget`."), ""]
    for scope in sorted({ls["scope"] for ls in lessons}, key=lambda s: (s != "global", s)):
        lines += [f"## {scope}", ""]
        for ls in (x for x in lessons if x["scope"] == scope):
            where = f"run `{ls['run_id']}`" + (f", step {ls['step']}" if ls["step"] else "")
            lines.append(f"- {ls['text']} ({where}, `{ls['lesson_id']}`)")
        lines.append("")
    return "\n".join(lines)


def export(con, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(to_markdown(all_lessons(con)))
    return path
